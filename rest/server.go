// Server is an HTTP server with a method-aware router.
type Server struct {
	router           *router.Router
	httpServer       *http.Server
	certFile         string
	keyFile          string
	shutdownTimeout  time.Duration
	handlerMu        sync.RWMutex
	handler          http.Handler
	frontMiddlewares []chain.Middleware
	outerMiddlewares []chain.Middleware
	tailMiddlewares  []chain.Middleware
	routesMu         sync.RWMutex
	routes           []Route
	addrMu           sync.RWMutex
	addr             string
	tlsConfig        *tls.Config
	servicesMu       sync.Mutex
	services         []service.Service
	log              logger.ILogger
	loggerSet        bool
}

// NewServer creates a server using the given configuration. The zero Config is
// replaced by DefaultConfig; a partially populated Config is used literally.
//
// When Config.Logger is configured, NewServer builds a logger from it, installs
// it as the server's own logger (used by the access-log middleware and other
// server-owned components) and also sets it as the global logger so that
// package-level logger functions in middleware (recovery, request-ID, ...) see
// the same instance. Use WithLogger to inject a pre-built logger instead: an
// injected logger takes precedence over Config.Logger and is not installed
// globally.
func NewServer(conf Config, opts ...Option) (*Server, error) {
	conf, err := conf.Setup()
	if err != nil {
		return nil, err
	}

	routes := router.New()
	shutdownTimeout := conf.ShutdownTimeout
	if shutdownTimeout <= 0 {
		shutdownTimeout = defaultShutdownTimeout
	}
	server := &Server{
		router:          routes,
		certFile:        conf.CertFile,
		keyFile:         conf.KeyFile,
		shutdownTimeout: shutdownTimeout,
		addr:            net.JoinHostPort(conf.Host, strconv.Itoa(conf.Port)),
	}
	// Apply options before building the middleware chain: WithLogger must reach
	// the access-log handler, and WithMiddleware/WithRateLimit append middleware
	// that has to run after the config-driven built-ins.
	for _, opt := range opts {
		opt(server)
	}

	// Build the server-owned logger after options so a logger injected with
	// WithLogger is used as-is and never installed as the global logger.
	var ownedLogger logger.ILogger
	if !server.loggerSet && conf.loggerConfigured() {
		ownedLogger = logger.New(conf.Logger)
		server.log = ownedLogger
	}
	if err := server.buildMiddlewares(conf); err != nil {
		return nil, err
	}
	if conf.Health.Enabled {
		// Normalize next to the registration so a disabled Health config is never
		// touched and an empty Path still becomes "/health".
		healthPath := healthpath.Normalize(conf.Health.Path)
		server.Handle(http.MethodGet, healthPath, func(w http.ResponseWriter, _ *http.Request) {
			_ = OkJSON(w, map[string]string{"status": "ok"})
		})
	}
	server.rebuildHandler()
	if ownedLogger != nil {
		logger.SetGlobal(ownedLogger)
		server.AddService(restservice.NewLoggerSync(ownedLogger))
	}
	if conf.Middlewares.Trace.Enabled && conf.Middlewares.Trace.Endpoint != "" {
		server.AddService(restservice.NewTraceAgent(conf.Middlewares.Trace.Config))
	}
	server.httpServer = &http.Server{
		Addr:           net.JoinHostPort(conf.Host, strconv.Itoa(conf.Port)),
		Handler:        server,
		ReadTimeout:    conf.ReadTimeout,
		WriteTimeout:   conf.WriteTimeout,
		IdleTimeout:    conf.IdleTimeout,
		MaxHeaderBytes: conf.MaxHeaderBytes,
		TLSConfig:      server.tlsConfig,
	}

	return server, nil
}

// buildMiddlewares assembles the server chain in execution order: the first
// entry wraps all later ones. s.frontMiddlewares holds the observability
// middleware. s.outerMiddlewares (including WithBreaker) follow observability
// middleware and wrap the tail/routes; the tail starts with Timeout. Middleware
// appended by options (WithMiddleware, WithRateLimit) runs after
// the config-driven tail.
func (s *Server) buildMiddlewares(conf Config) error {
	// Middleware added by options first (for example CORS, so even responses
	// generated by the built-ins carry its headers), then the config-driven ones.
	front := make([]chain.Middleware, 0, 8+len(s.frontMiddlewares))
	front = append(front, s.frontMiddlewares...)
	front = append(front,
		resthandler.NewRecoveryHandler(conf.Middlewares.Recovery).Handle,
		resthandler.NewRequestIDHandler(conf.Middlewares.RequestID).Handle,
		resthandler.NewTraceHandler(conf.Middlewares.Trace).Handle,
	)

	logHandler := resthandler.NewLogHandler(conf.Middlewares.Log, s.log)
	front = append(front,
		logHandler.Handle,
		resthandler.NewMaxConnsHandler(conf.Middlewares.MaxConns).Handle,
	)

	// Gunzip must run before MaxBytes: the limit has to apply to the
	// decompressed payload, otherwise a small gzip body can expand without
	// bound (decompression bomb).
	tail := []chain.Middleware{
		resthandler.NewTimeoutHandler(conf.Middlewares.Timeout).Handle,
		resthandler.NewGunzipHandler(conf.Middlewares.Gunzip).Handle,
		resthandler.NewMaxBytesHandler(conf.Middlewares.MaxBytes).Handle,
	}
	// Keep middleware appended by options behind the config-driven built-ins.
	tail = append(tail, s.tailMiddlewares...)

	s.frontMiddlewares = front
	s.tailMiddlewares = tail
	return nil
}

// Handle registers a handler function for the given method and path pattern.
func (s *Server) Handle(method, routePath string, handler http.HandlerFunc) {
	s.register(method, routePath, handler, true)
}

// register adds a route to the mux and optionally records it for Routes and
// PrintRoutes. Aliases such as the exact "/path/{$}" form are registered but not
// recorded.
func (s *Server) register(method, routePath string, handler http.HandlerFunc, record bool) {
	s.router.Handle(method, routePath, handler)
	if !record {
		return
	}

	s.routesMu.Lock()
	defer s.routesMu.Unlock()
	s.routes = append(s.routes, Route{Method: method, Path: routePath, Handler: handler})
}

// HandleFunc registers a handler function for the given method and path pattern.
func (s *Server) HandleFunc(method, routePath string, handler http.HandlerFunc) {
	s.Handle(method, routePath, handler)
}

// Router returns the server's router.
func (s *Server) Router() *router.Router {
	return s.router
}

// Logger returns the server-owned logger. It is nil when neither Config.Logger
// nor WithLogger supplied one, or when WithLogger(nil) explicitly cleared it.
// When nil, the access-log middleware and other components fall back to the
// global logger.
func (s *Server) Logger() logger.ILogger {
	return s.log
}

// SetNotFoundHandler sets the handler used when no route matches a request.
func (s *Server) SetNotFoundHandler(handler http.Handler) {
	s.router.SetNotFoundHandler(handler)
}

// SetNotAllowedHandler sets the handler used when a route path matches but the method does not.
func (s *Server) SetNotAllowedHandler(handler http.Handler) {
	s.router.SetNotAllowedHandler(handler)
}

// Use adds middleware to the server's request chain, after the built-ins.
func (s *Server) Use(middleware chain.Middleware) {
	s.handlerMu.Lock()
	defer s.handlerMu.Unlock()
	s.tailMiddlewares = append(s.tailMiddlewares, middleware)
	s.rebuildHandler()
}

func (s *Server) rebuildHandler() {
	routes := http.Handler(s.router)

	// Outer middleware wraps the built-in chain, so it also observes responses
	// generated by Timeout (for example a 503 that the breaker must count).
	middlewares := make([]chain.Middleware, 0,
		len(s.frontMiddlewares)+len(s.outerMiddlewares)+len(s.tailMiddlewares))
	middlewares = append(middlewares, s.frontMiddlewares...)
	middlewares = append(middlewares, s.outerMiddlewares...)
	middlewares = append(middlewares, s.tailMiddlewares...)
	s.handler = s.withPattern(chain.New(middlewares...).Then(routes))
}

// withPattern injects the matched route template into the request context so
// middleware sees the pattern instead of the concrete path.
func (s *Server) withPattern(next http.Handler) http.Handler {
	if next == nil {
		return next
	}
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if pattern := s.router.MatchedPattern(r); pattern != "" {
			r = r.WithContext(resthandler.ContextWithPattern(r.Context(), pattern))
		}
		next.ServeHTTP(w, r)
	})
}

// ServeHTTP dispatches a request through the server's router.
func (s *Server) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	s.handlerMu.RLock()
	handler := s.handler
	s.handlerMu.RUnlock()
	handler.ServeHTTP(w, r)
}

// Start serves requests until the server is stopped or encounters an error.
// The bound address is recorded so Addr reports the real port, including when
// Port is 0 and when TLS is enabled.
func (s *Server) Start() error {
	listener, err := net.Listen("tcp", s.httpServer.Addr)
	if err != nil {
		return err
	}
	return s.Serve(listener)
}

// Serve serves requests on the supplied listener and records its address so
// Addr reflects the bound port.
func (s *Server) Serve(listener net.Listener) error {
	if listener == nil {
		return errors.New("rest: listener must not be nil")
	}

	s.addrMu.Lock()
	s.addr = listener.Addr().String()
	s.addrMu.Unlock()

	if s.certFile != "" && s.keyFile != "" {
		err := s.httpServer.ServeTLS(listener, s.certFile, s.keyFile)
		// ServeTLS returns before taking ownership when the certificate cannot
		// be loaded; close the listener in that case so callers do not leak it.
		if err != nil && !errors.Is(err, http.ErrServerClosed) {
			_ = listener.Close()
		}
		return err
	}
	return s.httpServer.Serve(listener)
}

// Addr returns the address the server listens on. Before Serve or Start it is
// the configured address.
func (s *Server) Addr() string {
	s.addrMu.RLock()
	defer s.addrMu.RUnlock()
	return s.addr
}

// Shutdown gracefully shuts down the server.
func (s *Server) Shutdown(ctx context.Context) error {
	return s.httpServer.Shutdown(ctx)
}

// Stop gracefully shuts down the server, forcing connections closed on timeout.
func (s *Server) Stop() error {
	ctx, cancel := context.WithTimeout(context.Background(), s.shutdownTimeout)
	defer cancel()

	if err := s.Shutdown(ctx); err != nil {
		if closeErr := s.Close(); closeErr != nil {
			return errors.Join(err, closeErr)
		}
		return err
	}
	return nil
}

// Close immediately closes the server and its active connections.
func (s *Server) Close() error {
	return s.httpServer.Close()
}

// AddService appends an auxiliary service to the server. It is added to a
// ServiceGroup by Register. The logger sync and trace agent services are added
// automatically; call AddService for other lifecycle-aware dependencies (for
// example a taskq consumer). Add services before Register/Serve.
func (s *Server) AddService(svc service.Service) {
	if svc == nil {
		return
	}
	s.servicesMu.Lock()
	s.services = append(s.services, svc)
	s.servicesMu.Unlock()
}

// Register adds the HTTP server and every auxiliary service to group. Use this
// instead of service.AsService(server) when the server owns auxiliary services:
//
//	sg := service.NewServiceGroup()
//	server.Register(sg)
//	sg.Start()
func (s *Server) Register(group *service.ServiceGroup) {
	if group == nil {
		return
	}

	// Add auxiliary services first, then the HTTP server: ServiceGroup stops in
	// reverse order, so the logger is flushed after the server has stopped.
	s.servicesMu.Lock()
	services := append([]service.Service(nil), s.services...)
	s.servicesMu.Unlock()
	for _, svc := range services {
		group.Add(svc)
	}
	group.Add(service.AsService(s))
}

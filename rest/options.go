package rest

import (
	"crypto/tls"
	"net/http"

	"github.com/chihqiang/infra-go/core/breaker"
	"github.com/chihqiang/infra-go/core/logger"
	"github.com/chihqiang/infra-go/core/ratelimit"
	"github.com/chihqiang/infra-go/rest/chain"
	resthandler "github.com/chihqiang/infra-go/rest/handler"
	"github.com/chihqiang/infra-go/rest/internal/cors"
)

// Option customizes a Server during construction.
type Option func(*Server)

// WithMiddleware appends middleware after the config-driven built-ins.
func WithMiddleware(middlewares ...chain.Middleware) Option {
	return func(s *Server) {
		s.tailMiddlewares = append(s.tailMiddlewares, middlewares...)
	}
}

// WithRateLimit installs a rate limiter after the built-in middleware, so
// rejected requests are still traced/logged.
func WithRateLimit(limiter ratelimit.Limiter) Option {
	return WithMiddleware(resthandler.NewRateLimitHandler(resthandler.RateLimitConfig{
		Enabled: true,
		Limiter: limiter,
	}).Handle)
}

// WithBreaker wraps route handlers with the given circuit breaker. It is placed
// outside the built-in middleware, so responses generated by Timeout (503) and
// Recovery (500) are reported to the breaker as failures.
func WithBreaker(br breaker.Breaker) Option {
	return func(s *Server) {
		if br == nil {
			return
		}
		s.outerMiddlewares = append(s.outerMiddlewares,
			resthandler.NewBreakerHandler(resthandler.BreakerConfig{Enabled: true, Breaker: br}).Handle)
	}
}

// WithSignature requires an HMAC signature on every request. The signature covers
// the method, escaped path, raw query, timestamp and body; TTL defaults to five
// minutes when omitted.
func WithSignature(cfg resthandler.SignatureConfig) Option {
	cfg.Enabled = true
	return WithMiddleware(resthandler.NewSignatureHandler(cfg).Handle)
}

// WithAuth requires a valid bearer token on every request. cfg carries the
// parser or the token secret and the rejection behaviour (realm, callback);
// Enabled is set automatically. The parser is built from the embedded
// token.Config when cfg.Parser is nil, so the secret can come from a
// configuration file. For route or group scoped auth use WithRouteAuth or mount
// handler.NewAuthHandler yourself.
func WithAuth(cfg resthandler.AuthConfig) Option {
	if cfg.Parser == nil && cfg.Secret == "" {
		panic("rest: WithAuth requires a token parser or secret")
	}
	cfg.Enabled = true
	return WithMiddleware(resthandler.NewAuthHandler(cfg).Handle)
}

// WithTLSConfig applies cfg to the underlying http.Server. It takes effect when
// both CertFile and KeyFile are configured.
func WithTLSConfig(cfg *tls.Config) Option {
	return func(s *Server) {
		s.tlsConfig = cfg
	}
}

// WithLogger injects a pre-built logger into the server. The access-log
// middleware uses it directly instead of falling back to the global logger. It
// takes precedence over Config.Logger: when both are set, the config logger is
// not built. A nil logger clears the server-owned logger, reverting to the
// global logger.
//
// This option does not call logger.SetGlobal; callers that want the global to
// match should call it themselves. It is useful in tests and in multi-server
// setups where each server should own its logger independently.
func WithLogger(l logger.ILogger) Option {
	return func(s *Server) {
		s.log = l
		s.loggerSet = true
	}
}

type corsSetting struct {
	origins      []string
	headers      []string
	headerFn     func(http.Header)
	notAllowedFn func(http.ResponseWriter)
}

// WithCORS enables CORS for the given origins, or all origins when none are given.
func WithCORS(origins ...string) Option {
	return func(s *Server) {
		setting := s.cors
		if setting == nil {
			setting = &corsSetting{}
		}
		setting.origins = append([]string(nil), origins...)
		setting.headers = append(setting.headers, s.pendingCorsHeaders...)
		s.pendingCorsHeaders = nil
		s.cors = setting
	}
}

// WithCORSHeaders adds extra allowed request headers to CORS responses. It only
// configures headers: CORS still has to be enabled with WithCORS or
// WithCustomCORS.
func WithCORSHeaders(headers ...string) Option {
	return func(s *Server) {
		if s.cors == nil {
			s.pendingCorsHeaders = append(s.pendingCorsHeaders, headers...)
			return
		}
		s.cors.headers = append(s.cors.headers, headers...)
	}
}

// WithCustomCORS enables CORS with custom header and rejection callbacks.
func WithCustomCORS(headerFn func(http.Header), notAllowedFn func(http.ResponseWriter), origins ...string) Option {
	return func(s *Server) {
		s.cors = &corsSetting{
			origins:      append([]string(nil), origins...),
			headers:      append([]string(nil), s.pendingCorsHeaders...),
			headerFn:     headerFn,
			notAllowedFn: notAllowedFn,
		}
		s.pendingCorsHeaders = nil
	}
}

func (c *corsSetting) headersFn() func(http.Header, *http.Request) {
	if c == nil {
		return nil
	}
	if len(c.headers) == 0 && c.headerFn == nil {
		return nil
	}

	return func(header http.Header, r *http.Request) {
		if c.headerFn != nil {
			c.headerFn(header)
		}
		// Extra allowed request headers only belong on a preflight response.
		if len(c.headers) > 0 && cors.IsPreflight(r) {
			cors.AddAllowHeaders(header, c.headers...)
		}
	}
}

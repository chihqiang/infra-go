package rest

import (
	"crypto/tls"
	"net/http"

	"github.com/chihqiang/ten-go/core/breaker"
	"github.com/chihqiang/ten-go/core/logger"
	"github.com/chihqiang/ten-go/core/ratelimit"
	"github.com/chihqiang/ten-go/rest/chain"
	resthandler "github.com/chihqiang/ten-go/rest/handler"
)

// Option customizes a Server during construction.
type Option func(*Server)

// WithMiddleware appends middleware after the config-driven built-ins.
func WithMiddleware(middlewares ...chain.Middleware) Option {
	return func(s *Server) {
		s.tailMiddlewares = append(s.tailMiddlewares, middlewares...)
	}
}

// WithRateLimit installs a rate limiter after the built-in middleware, so
// rejected requests are still traced/logged.
func WithRateLimit(limiter ratelimit.Limiter) Option {
	return WithMiddleware(resthandler.NewRateLimitHandler(limiter).Handle)
}

// WithBreaker wraps route handlers with the given circuit breaker. It is placed
// outside the built-in middleware, so responses generated by Timeout (503) and
// Recovery (500) are reported to the breaker as failures.
func WithBreaker(br breaker.Breaker) Option {
	return func(s *Server) {
		if br == nil {
			return
		}
		s.outerMiddlewares = append(s.outerMiddlewares,
			resthandler.NewBreakerHandler(br).Handle)
	}
}

// WithAuth requires a valid bearer token signed with secret on every request.
// Use the
// AuthOption values (WithPrevSecret, WithAuthSkipPaths,
// WithUnauthorizedCallback, WithTokenExtractor) to customise the handler; for
// route or group scoped auth use WithRouteAuth.
func WithAuth(secret string, opts ...resthandler.AuthOption) Option {
	return WithMiddleware(resthandler.NewAuthHandler(
		resthandler.AuthConfig{Secret: secret}, opts...).Handle)
}

// WithNotFoundHandler sets the handler used when no route matches a request.
// It is the option form of SetNotFoundHandler, for callers that build the
// server in one expression.
func WithNotFoundHandler(handler http.Handler) Option {
	return func(s *Server) {
		s.SetNotFoundHandler(handler)
	}
}

// WithNotAllowedHandler sets the handler used when a route path matches but the
// method does not. It is the option form of SetNotAllowedHandler.
func WithNotAllowedHandler(handler http.Handler) Option {
	return func(s *Server) {
		s.SetNotAllowedHandler(handler)
	}
}

// WithTLSConfig applies cfg to the underlying http.Server. It takes effect when
// both CertFile and KeyFile are configured.
func WithTLSConfig(cfg *tls.Config) Option {
	return func(s *Server) {
		s.tlsConfig = cfg
	}
}

// WithLogger injects a pre-built logger into the server. The access-log
// middleware uses it directly instead of falling back to the global logger. It
// takes precedence over Config.Logger: when both are set, the config logger is
// not built. A nil logger clears the server-owned logger, reverting to the
// global logger.
//
// This option does not call logger.SetGlobal; callers that want the global to
// match should call it themselves. It is useful in tests and in multi-server
// setups where each server should own its logger independently.
func WithLogger(l logger.ILogger) Option {
	return func(s *Server) {
		s.log = l
		s.loggerSet = true
	}
}

// WithCORS enables CORS for the given origins, or all origins when none are
// given. The handler is mounted at the front of the middleware chain, so
// preflight requests are answered before the built-in middleware runs.
func WithCORS(origins ...string) Option {
	return func(s *Server) {
		s.frontMiddlewares = append(s.frontMiddlewares, resthandler.NewCORSHandler(
			resthandler.CORSConfig{Origins: append([]string(nil), origins...)}).Handle)
	}
}

// WithCORSHeaders adds extra allowed request headers to preflight responses.
// It only configures headers: CORS still has to be enabled with WithCORS. The
// middleware runs before the CORS handler, which merges the values, so the
// option order does not matter.
func WithCORSHeaders(headers ...string) Option {
	return func(s *Server) {
		s.frontMiddlewares = append([]chain.Middleware{
			resthandler.NewCORSHandler(resthandler.CORSConfig{Headers: headers}).AppendHeaders,
		}, s.frontMiddlewares...)
	}
}
